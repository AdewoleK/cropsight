"""Builds the app's translation files from ui.py and domain.py.

    python3 tool/l10n/build.py

Writes:
  tool/l10n/strings.csv            every phrase in all five languages, for
                                   native-speaker review in a spreadsheet
  lib/l10n/translations_*.dart     the maps the app reads

Fails if any phrase the app uses (tool/l10n/extract.py) has no translation,
or a translation drops or invents a {placeholder}.
"""

import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

from domain import ALL as DOMAIN  # noqa: E402
from extract import all_keys  # noqa: E402
from ui import UI  # noqa: E402

LANGS = [("ha", "hausa", "Hausa"), ("yo", "yoruba", "Yoruba"),
         ("ig", "igbo", "Igbo"), ("pcm", "pidgin", "Nigerian Pidgin")]
PLACEHOLDER = re.compile(r"\{\w+\}")


def rows():
    table = {}
    for row in UI + DOMAIN:
        if len(row) != 5:
            raise SystemExit(f"row needs 5 columns: {row!r}")
        en, *rest = row
        table[en] = [en if t == "=" else t for t in rest]
    return table


def check(table):
    problems = []
    for key in all_keys():
        if key not in table:
            problems.append(f"no translation for {key!r}")
    for en, tr in table.items():
        want = sorted(PLACEHOLDER.findall(en))
        for (code, _, _), text in zip(LANGS, tr):
            if sorted(PLACEHOLDER.findall(text)) != want:
                problems.append(f"{code}: placeholders differ for {en!r}")
    if problems:
        raise SystemExit("\n".join(problems))


def dart_string(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def main():
    table = rows()
    check(table)
    used = all_keys()
    with open(HERE / "strings.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["English", "Hausa", "Yoruba", "Igbo", "Nigerian Pidgin", "Reviewed by"])
        for en in used:
            w.writerow([en, *table[en], ""])
    for i, (code, var, name) in enumerate(LANGS):
        lines = [
            f"// {name} wording for the app's screens, keyed by the English text.",
            "// GENERATED by tool/l10n/build.py from tool/l10n/ui.py and domain.py — edit those.",
            "// DRAFT: to be checked by native speakers who know farming before wide use.",
            "// ignore_for_file: lines_longer_than_80_chars",
            f"const Map<String, String> {var} = {{",
        ]
        for en in used:
            lines.append(f"  {dart_string(en)}: {dart_string(table[en][i])},")
        lines.append("};\n")
        (ROOT / f"lib/l10n/translations_{code}.dart").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(used)} phrases × {len(LANGS)} languages written")


if __name__ == "__main__":
    main()
